"""Writes Symbols.kt: the Material Symbols Rounded icons listed in symbols.txt, as Compose ImageVectors.

The icons come from the Android vector drawables Google publishes for Material Symbols (weight 400,
grade 0, optical size 24), fetched once into a cache next to this script.
"""
import os
import re
import sys
import urllib.request
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
CACHE = os.path.join(HERE, ".cache")
OUT = os.path.join(ROOT, "app/src/main/java/oolong/client/ui/common/theme/compose/Symbols.kt")
URL = "https://raw.githubusercontent.com/google/material-design-icons/master/symbols/android/{name}/materialsymbolsrounded/{file}"
ANDROID = "{http://schemas.android.com/apk/res/android}"


def listed():
    for line in open(os.path.join(HERE, "symbols.txt")):
        line = line.split("#", 1)[0].strip()
        if line:
            parts = line.split()
            yield parts[0], len(parts) > 1 and parts[1] == "fill"


def drawable(name, fill):
    file = f"{name}{'_fill1' if fill else ''}_24px.xml"
    path = os.path.join(CACHE, file)
    if not os.path.exists(path):
        os.makedirs(CACHE, exist_ok=True)
        data = urllib.request.urlopen(URL.format(name=name, file=file), timeout=30).read()
        with open(path, "wb") as f:
            f.write(data)
    return ET.parse(path).getroot()


def kotlin_name(name, fill):
    return "".join(part.capitalize() for part in name.split("_")) + ("Fill" if fill else "")


def main():
    entries = []
    for name, fill in sorted(set(listed())):
        root = drawable(name, fill)
        assert root.get(ANDROID + "viewportWidth") == "960" and root.get(ANDROID + "viewportHeight") == "960", name
        mirror = root.get(ANDROID + "autoMirrored") == "true"
        paths = [p.get(ANDROID + "pathData") for p in root.iter("path")]
        assert paths and all(re.fullmatch(r"[0-9MmLlHhVvCcSsQqTtAaZz.,\- ]+", p) for p in paths), name
        args = ", ".join(f'"{p}"' for p in paths)
        k = kotlin_name(name, fill)
        entries.append(f'    val {k}: ImageVector by lazy {{ symbol("{k}", {"true" if mirror else "false"}, {args}) }}\n')
    with open(OUT, "w") as f:
        f.write('''package oolong.client.ui.common.theme.compose

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.addPathNodes
import androidx.compose.ui.unit.dp

/**
 * The app's icons: Material Symbols Rounded at weight 400, outlined, with a filled form (`…Fill`)
 * only where the icon shows something is on, such as a like or a choice made.
 *
 * Generated by tools/symbols/generate.py from tools/symbols/symbols.txt; edit those, not this.
 */
object Symbols {
''')
        f.writelines(entries)
        f.write('''}

/** An icon drawn on Material Symbols' 960 unit grid at 24dp; [autoMirror] flips it right to left. */
private fun symbol(name: String, autoMirror: Boolean, vararg paths: String): ImageVector =
    ImageVector.Builder(name, 24.dp, 24.dp, 960f, 960f, autoMirror = autoMirror).apply {
        paths.forEach { addPath(addPathNodes(it), fill = SolidColor(Color.Black)) }
    }.build()
''')
    print(f"wrote {len(entries)} icons to {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    sys.exit(main())
